import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.existsSync('web/ui-feedback.js')?'web/ui-feedback.js':'ui-feedback.js';
let response,requests=0;
const context={window:{},AbortController,setTimeout,clearTimeout,fetch:async(...args)=>{requests++;return response(...args);}};
vm.runInNewContext(fs.readFileSync(source,'utf8'),context);
const feedback=context.window.FarstarFeedback;
response=async()=>({ok:false,status:400,json:async()=>({error:'پورت آزاد نیست.',error_code:'port_unavailable',error_title:'پورت قابل استفاده نیست',error_hint:'پورت دیگری انتخاب کن.',error_id:'fixture-1'})});
await assert.rejects(feedback.request('/api/routes/add',{method:'POST'},{operation:'routes/add'}),e=>e.code==='port_unavailable'&&e.hint.includes('دیگری')&&e.id==='fixture-1');
assert.equal(requests,1,'writes must not be automatically retried');
response=async()=>({ok:false,status:502,json:async()=>{throw new SyntaxError('<html>not json</html>');}});
await assert.rejects(feedback.request('/api/state'),e=>e.code==='invalid_response'&&!e.message.includes('<html>'));
response=async()=>({ok:true,status:200,json:async()=>null});
await assert.rejects(feedback.request('/api/state'),e=>e.code==='invalid_response');
response=async()=>{throw new TypeError('fetch failed');};
await assert.rejects(feedback.request('/api/state'),e=>e.code==='network_error');
response=async(url,options)=>new Promise((resolve,reject)=>options.signal.addEventListener('abort',()=>{const error=new Error('abort');error.name='AbortError';reject(error);},{once:true}));
await assert.rejects(feedback.request('/api/hosts/create',{method:'POST'},{timeoutMs:2}),e=>e.code==='request_timeout'&&e.hint.includes('قبل'));
assert.ok(!feedback.explain('socks5://person:SECRET@example.org token=PRIVATE FS-'+'x'.repeat(40)).message.includes('SECRET'));
console.log('Feedback passed: structured causes, invalid JSON/null, transport errors, timeout, no write retry, secret redaction.');
